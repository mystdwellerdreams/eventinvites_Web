import { readFileSync, writeFileSync } from 'node:fs'

/**
 * Writes .dev.vars, the file `wrangler dev` reads for local secrets.
 *
 * The values come from the repository's .env.local, which holds the same
 * secrets for local development, so the two are not maintained separately.
 * The file is gitignored.
 */
const source = readFileSync('.env.local', 'utf8')
const values = new Map()
for (const line of source.split(/\r?\n/)) {
  const match = line.match(/^([A-Z_][A-Z0-9_]*)=(.*)$/)
  if (!match) continue
  values.set(match[1], match[2].trim().replace(/^["']|["']$/g, ''))
}

// The Worker reads the pooled endpoint through Hyperdrive; locally the
// binding falls back to this one, so it is the direct connection string.
const databaseUrl = values.get('DIRECT_DATABASE_URL') ?? values.get('DATABASE_URL')
if (!databaseUrl) {
  console.error(
    'No DATABASE_URL in .env.local, so .dev.vars would have no database to\n' +
      'point at. Add it there; the file is gitignored.'
  )
  process.exit(1)
}

const lines = [
  '# Generated by scripts/write-dev-vars.mjs. Gitignored.',
  '# The secrets `wrangler dev` reads. The production ones live in the',
  '# Worker as secrets: npx wrangler secret put <NAME>',
  '',
  `DATABASE_URL="${databaseUrl}"`,
  `JWT_SECRET="${values.get('JWT_SECRET') ?? ''}"`,
  `REFRESH_SECRET="${values.get('REFRESH_SECRET') ?? ''}"`,
  `BLOB_READ_WRITE_TOKEN="${values.get('BLOB_READ_WRITE_TOKEN') ?? ''}"`,
  `BLOB_STORE_ID="${values.get('BLOB_STORE_ID') ?? ''}"`,
  `AWS_ENDPOINT_URL_S3="${values.get('AWS_ENDPOINT_URL_S3') ?? ''}"`,
  `AWS_ACCESS_KEY_ID="${values.get('AWS_ACCESS_KEY_ID') ?? ''}"`,
  `AWS_SECRET_ACCESS_KEY="${values.get('AWS_SECRET_ACCESS_KEY') ?? ''}"`,
  `AWS_REGION="${values.get('AWS_REGION') ?? ''}"`,
  `NEON_STORAGE_BUCKET="${values.get('NEON_STORAGE_BUCKET') ?? ''}"`,
  `NEON_STORAGE_ACCESS="${values.get('NEON_STORAGE_ACCESS') ?? ''}"`,
  `STORAGE_BACKEND="${values.get('STORAGE_BACKEND') ?? 'blob'}"`,
  `TURNSTILE_SECRET_KEY="${values.get('TURNSTILE_SECRET_KEY') ?? ''}"`,
  '',
]

writeFileSync('.dev.vars', lines.join('\n'))
console.log('wrote .dev.vars with', lines.filter((l) => l.includes('=')).length, 'entries')
